  MODIFY COLUMN id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
  MODIFY COLUMN site_id VARCHAR(64) NOT NULL COMMENT '站点标识：sd-ggzyjyzx / jd-quan-yicai',
