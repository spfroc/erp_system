  MODIFY COLUMN notice_type VARCHAR(32) NULL COMMENT '站点侧公告类型编码',
  MODIFY COLUMN title VARCHAR(512) NULL COMMENT '公告标题',
  MODIFY COLUMN region_name VARCHAR(128) NULL COMMENT '区域名称',
  MODIFY COLUMN publish_time DATETIME NULL COMMENT '发布时间',
  MODIFY COLUMN list_json JSON NULL COMMENT '列表接口原始条目',
  MODIFY COLUMN detail_json JSON NULL COMMENT '详情接口原始 JSON',
  MODIFY COLUMN content_html MEDIUMTEXT NULL COMMENT '详情正文 HTML',
  MODIFY COLUMN content_text MEDIUMTEXT NULL COMMENT '去标签正文，供模型解析',
  MODIFY COLUMN source_url VARCHAR(1024) NULL COMMENT '来源页面 URL',
  MODIFY COLUMN crawl_status VARCHAR(32) NOT NULL DEFAULT 'list_only' COMMENT '抓取状态：list_only/detail_ok/detail_fail',
  MODIFY COLUMN parse_status VARCHAR(32) NOT NULL DEFAULT 'pending' COMMENT '解析状态：pending/parsed/parse_fail/skipped',
  MODIFY COLUMN error_message VARCHAR(1000) NULL COMMENT '抓取/解析错误信息',
  MODIFY COLUMN crawled_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '列表抓取时间',
  MODIFY COLUMN detail_at DATETIME NULL COMMENT '详情抓取时间',
  MODIFY COLUMN updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间';

