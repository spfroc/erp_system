-- 政府采购公告抓取表（复用主库 yicai_erp，不另建库）
-- MySQL 8.0+ / utf8mb4

-- 原始公告（列表+详情整包保留）
CREATE TABLE IF NOT EXISTS notice_raw (
  id              BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
  site_id         VARCHAR(64)  NOT NULL COMMENT '站点标识：sd-ggzyjyzx / jd-quan-yicai',
  notice_key      VARCHAR(128) NOT NULL COMMENT '站点内唯一键 noticeGuid/auctionNo+noticeType',
  auction_type    VARCHAR(32)  NULL COMMENT '站点侧采购方式编码',
  notice_type     VARCHAR(32)  NULL COMMENT '站点侧公告类型编码',
  title           VARCHAR(512) NULL COMMENT '公告标题',
  region_name     VARCHAR(128) NULL COMMENT '区域名称',
  publish_time    DATETIME     NULL COMMENT '发布时间',
  list_json       JSON         NULL COMMENT '列表接口原始条目',
  detail_json     JSON         NULL COMMENT '详情接口原始 JSON',
  content_html    MEDIUMTEXT   NULL COMMENT '详情正文 HTML',
  content_text    MEDIUMTEXT   NULL COMMENT '去标签正文，供模型解析',
  source_url      VARCHAR(1024) NULL COMMENT '来源页面 URL',
  crawl_status    VARCHAR(32)  NOT NULL DEFAULT 'list_only' COMMENT '抓取状态：list_only/detail_ok/detail_fail',
  parse_status    VARCHAR(32)  NOT NULL DEFAULT 'pending' COMMENT '解析状态：pending/parsed/parse_fail/skipped',
  error_message   VARCHAR(1000) NULL COMMENT '抓取/解析错误信息',
  crawled_at      DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '列表抓取时间',
  detail_at       DATETIME     NULL COMMENT '详情抓取时间',
  updated_at      DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (id),
  UNIQUE KEY uk_site_notice (site_id, notice_key),
  KEY idx_site_type (site_id, auction_type, notice_type),
  KEY idx_parse_status (parse_status),
  KEY idx_publish_time (publish_time)
) ENGINE=InnoDB COMMENT='公告原始数据';

-- 模型解析后的关键字段
CREATE TABLE IF NOT EXISTS notice_parsed (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
  notice_raw_id     BIGINT UNSIGNED NOT NULL COMMENT '关联 notice_raw.id',
  site_id           VARCHAR(64)  NOT NULL COMMENT '站点标识',
  notice_key        VARCHAR(128) NOT NULL COMMENT '公告唯一键',
  project_code      VARCHAR(128) NULL COMMENT '项目编号',
  project_name      VARCHAR(512) NULL COMMENT '项目名称',
  notice_title      VARCHAR(512) NULL COMMENT '公告标题',
  buyer_name        VARCHAR(256) NULL COMMENT '采购单位',
  buyer_contact_name VARCHAR(128) NULL COMMENT '项目联系人',
  buyer_phone       VARCHAR(64)  NULL COMMENT '项目联系电话',
  buyer_address     VARCHAR(512) NULL COMMENT '采购人/项目地址',
  buyer_contact     VARCHAR(256) NULL COMMENT '兼容：联系人/电话合并',
  region_name       VARCHAR(128) NULL COMMENT '区域名称',
  budget_amount     DECIMAL(18,2) NULL COMMENT '预算金额',
  deal_amount       DECIMAL(18,2) NULL COMMENT '成交金额',
  deal_supplier     VARCHAR(256) NULL COMMENT '成交供应商',
  deal_supplier_phone VARCHAR(64) NULL COMMENT '成交供应商电话',
  deal_supplier_address VARCHAR(512) NULL COMMENT '成交供应商地址',
  quote_count       INT NULL COMMENT '报价家数',
  notice_kind       VARCHAR(64)  NULL COMMENT '公告种类：采购/成交/终止/废标等',
  procurement_mode  VARCHAR(64)  NULL COMMENT '采购方式：竞价/反拍/询比/框架二次竞价等',
  publish_time      DATETIME NULL COMMENT '发布时间',
  start_time        DATETIME NULL COMMENT '开始时间',
  end_time          DATETIME NULL COMMENT '截止时间',
  delivery_address  VARCHAR(512) NULL COMMENT '交货地点',
  quotes_json       JSON NULL COMMENT '报价名单数组',
  suppliers_json    JSON NULL COMMENT '相关供应商（含未成交）',
  extra_json        JSON NULL COMMENT '其它模型抽出字段',
  model_name        VARCHAR(128) NULL COMMENT '解析所用模型/后端',
  model_raw_json    JSON NULL COMMENT '模型原始输出',
  confidence        DECIMAL(5,4) NULL COMMENT '置信度 0~1',
  parsed_at         DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '解析时间',
  updated_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (id),
  UNIQUE KEY uk_raw (notice_raw_id),
  KEY idx_project_code (project_code),
  KEY idx_buyer (buyer_name),
  KEY idx_deal_supplier (deal_supplier),
  CONSTRAINT fk_parsed_raw FOREIGN KEY (notice_raw_id) REFERENCES notice_raw(id) ON DELETE CASCADE
) ENGINE=InnoDB COMMENT='公告关键字段（模型解析）';

-- 产品明细（一对多，不用 JSON）
CREATE TABLE IF NOT EXISTS notice_goods (
  id                BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
  notice_raw_id     BIGINT UNSIGNED NOT NULL COMMENT '关联 notice_raw.id',
  notice_parsed_id  BIGINT UNSIGNED NULL COMMENT '关联 notice_parsed.id',
  site_id           VARCHAR(64)  NOT NULL COMMENT '站点标识',
  notice_key        VARCHAR(128) NOT NULL COMMENT '公告唯一键',
  line_no           INT NOT NULL DEFAULT 1 COMMENT '明细行号，从1开始',
  product_name      VARCHAR(512) NULL COMMENT '产品名称',
  category          VARCHAR(256) NULL COMMENT '产品分类',
  quantity          DECIMAL(18,4) NULL COMMENT '购买数量',
  unit              VARCHAR(64)  NULL COMMENT '计量单位',
  brand             VARCHAR(128) NULL COMMENT '品牌',
  model             VARCHAR(256) NULL COMMENT '型号',
  unit_price        DECIMAL(18,4) NULL COMMENT '单价',
  spec              VARCHAR(2000) NULL COMMENT '参数/规格',
  amount            DECIMAL(18,2) NULL COMMENT '金额小计',
  created_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  updated_at        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (id),
  KEY idx_goods_raw (notice_raw_id),
  KEY idx_goods_parsed (notice_parsed_id),
  KEY idx_goods_site_key (site_id, notice_key),
  KEY idx_goods_name (product_name(191)),
  CONSTRAINT fk_goods_raw FOREIGN KEY (notice_raw_id) REFERENCES notice_raw(id) ON DELETE CASCADE,
  CONSTRAINT fk_goods_parsed FOREIGN KEY (notice_parsed_id) REFERENCES notice_parsed(id) ON DELETE CASCADE
) ENGINE=InnoDB COMMENT='公告产品明细';

-- 附件（京东为主，其它站点若有也复用）
CREATE TABLE IF NOT EXISTS notice_attachment (
  id              BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
  notice_raw_id   BIGINT UNSIGNED NOT NULL COMMENT '关联 notice_raw.id',
  site_id         VARCHAR(64)  NOT NULL COMMENT '站点标识',
  notice_key      VARCHAR(128) NOT NULL COMMENT '公告唯一键',
  file_name       VARCHAR(512) NULL COMMENT '附件文件名',
  file_url        VARCHAR(2048) NOT NULL COMMENT '附件下载 URL',
  local_path      VARCHAR(1024) NULL COMMENT '本地保存路径',
  file_ext        VARCHAR(32)  NULL COMMENT '文件扩展名',
  file_size       BIGINT UNSIGNED NULL COMMENT '文件大小（字节）',
  content_sha256  CHAR(64) NULL COMMENT '文件内容 SHA256',
  download_status VARCHAR(32) NOT NULL DEFAULT 'pending' COMMENT '下载状态：pending/done/fail/skip',
  parse_status    VARCHAR(32) NOT NULL DEFAULT 'pending' COMMENT '解析状态：pending/parsed/parse_fail/skipped',
  extracted_text  MEDIUMTEXT NULL COMMENT '附件抽取文本',
  parsed_json     JSON NULL COMMENT '附件模型解析结果',
  error_message   VARCHAR(1000) NULL COMMENT '下载/解析错误信息',
  downloaded_at   DATETIME NULL COMMENT '下载完成时间',
  parsed_at       DATETIME NULL COMMENT '解析完成时间',
  created_at      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  updated_at      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (id),
  UNIQUE KEY uk_raw_url (notice_raw_id, file_url(255)),
  KEY idx_download_status (download_status),
  CONSTRAINT fk_att_raw FOREIGN KEY (notice_raw_id) REFERENCES notice_raw(id) ON DELETE CASCADE
) ENGINE=InnoDB COMMENT='公告附件及解析';

-- 抓取游标 / 任务状态
CREATE TABLE IF NOT EXISTS crawl_cursor (
  id            BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键',
  site_id       VARCHAR(64) NOT NULL COMMENT '站点标识',
  cursor_key    VARCHAR(128) NOT NULL COMMENT '游标键，如 auctionType:noticeType',
  last_page     INT NOT NULL DEFAULT 0 COMMENT '上次抓取到的页码',
  last_total    INT NULL COMMENT '上次接口返回的总条数',
  last_success_at DATETIME NULL COMMENT '上次成功抓取时间',
  extra_json    JSON NULL COMMENT '扩展状态 JSON',
  updated_at    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (id),
  UNIQUE KEY uk_site_cursor (site_id, cursor_key)
) ENGINE=InnoDB COMMENT='分页游标';

-- 山东商城供应商（对齐 vip-rebuild TouchCustomer / customers）
CREATE TABLE IF NOT EXISTS mall_customer (
  id BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键',
  name VARCHAR(256) NOT NULL COMMENT '公司名称',
  platform_customer_id VARCHAR(64) DEFAULT NULL COMMENT '平台供应商 id / supplierGuid',
  type VARCHAR(128) DEFAULT NULL COMMENT '入驻类型',
  address TEXT COMMENT '地址',
  province VARCHAR(64) DEFAULT NULL COMMENT '省',
  city VARCHAR(64) DEFAULT NULL COMMENT '市',
  license VARCHAR(256) DEFAULT NULL COMMENT '营业执照附件',
  license_code VARCHAR(128) DEFAULT NULL COMMENT '统一社会信用代码',
  business_scope TEXT COMMENT '经营范围 / 品目',
  enter_time VARCHAR(64) DEFAULT NULL COMMENT '入驻时间',
  legal_person VARCHAR(128) DEFAULT NULL COMMENT '法人/联系人',
  mobile VARCHAR(512) DEFAULT NULL COMMENT '联系电话',
  new_mobile VARCHAR(512) DEFAULT NULL COMMENT '新平台手机号',
  email VARCHAR(256) DEFAULT NULL COMMENT '邮箱',
  origin VARCHAR(64) DEFAULT '10' COMMENT '来源：4旧齐鲁云采 10新齐鲁云采',
  agent_shop_product_number INT DEFAULT NULL COMMENT '店铺商品数量',
  list_json JSON COMMENT '列表接口原始条目',
  store_json JSON COMMENT '店铺详情原始 JSON',
  crawled_at DATETIME DEFAULT NULL COMMENT '首次抓取时间',
  updated_at DATETIME DEFAULT NULL COMMENT '更新时间',
  PRIMARY KEY (id),
  UNIQUE KEY uk_mall_customer_name (name),
  KEY idx_platform_customer_id (platform_customer_id),
  KEY idx_type (type),
  KEY idx_city (city)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='山东商城供应商客户';
